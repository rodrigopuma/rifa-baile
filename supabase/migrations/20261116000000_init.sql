-- =============================================================================
-- Rifa Solidária — Formatura de Aspirantes-a-Oficial do CPOR/R
-- Esquema inicial (Supabase PostgreSQL). Datas sempre em timestamptz (UTC).
--
-- Modelo de acesso:
--   * O backend FastAPI conecta com o papel "postgres" (DATABASE_URL), que ignora RLS.
--   * Os papéis "anon" e "authenticated" NÃO têm acesso a nenhuma tabela com dados
--     pessoais (RLS habilitado, sem políticas).
--   * A única tabela legível publicamente é number_availability, que contém somente
--     (campaign_id, number, available) e é transmitida pelo Supabase Realtime.
-- =============================================================================

create extension if not exists pgcrypto;

-- ---------------------------------------------------------------------------
-- campaigns
-- ---------------------------------------------------------------------------
create table public.campaigns (
  id                 uuid primary key default gen_random_uuid(),
  name               varchar(160) not null,
  subtitle           varchar(240) not null default '',
  description        text not null default '',
  price_cents        integer not null constraint ck_campaigns_price check (price_cents > 0),
  total_numbers      integer not null constraint ck_campaigns_total check (total_numbers > 0 and total_numbers <= 100000),
  draw_date          date,
  organizer_name     varchar(200) not null default '',
  organizer_contact  varchar(200) not null default '',
  regulation_text    text not null default '',
  authorization_info text not null default '',
  header_image_url   varchar(500) not null default '',
  status             varchar(16) not null default 'draft'
                     constraint ck_campaigns_status check (status in ('draft','active','paused','closed')),
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now()
);
-- Apenas uma campanha ativa por vez
create unique index uq_campaigns_one_active on public.campaigns (status) where status = 'active';

-- ---------------------------------------------------------------------------
-- participants (dados pessoais — acesso apenas pelo backend)
-- ---------------------------------------------------------------------------
create table public.participants (
  id                  uuid primary key default gen_random_uuid(),
  full_name           varchar(160) not null,
  email               varchar(254) not null,
  phone               varchar(20)  not null,
  cpf_masked          varchar(20)  not null default '',   -- o CPF completo não é armazenado
  privacy_accepted_at timestamptz not null default now(),
  created_at          timestamptz not null default now()
);
create index ix_participants_email_phone on public.participants (email, phone);

-- ---------------------------------------------------------------------------
-- orders
-- ---------------------------------------------------------------------------
create table public.orders (
  id                   uuid primary key default gen_random_uuid(),
  code                 varchar(16) not null unique,
  campaign_id          uuid not null references public.campaigns(id),
  participant_id       uuid not null references public.participants(id),
  status               varchar(16) not null default 'pending'
                       constraint ck_orders_status check (status in ('pending','paid','cancelled','expired','refunded','in_review')),
  unit_price_cents     integer not null,
  quantity             integer not null,
  total_cents          integer not null,
  access_token_hash    varchar(64) not null,
  checkout_expires_at  timestamptz not null,
  payment_expires_at   timestamptz not null,
  cancel_requested_at  timestamptz,
  paid_at              timestamptz,
  closed_at            timestamptz,
  review_reason        text not null default '',
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now(),
  constraint ck_orders_total check (total_cents = unit_price_cents * quantity)
);
create index ix_orders_status_checkout on public.orders (status, checkout_expires_at);
create index ix_orders_participant on public.orders (participant_id);

-- ---------------------------------------------------------------------------
-- numbers
-- ---------------------------------------------------------------------------
create table public.numbers (
  id          bigint generated by default as identity primary key,
  campaign_id uuid not null references public.campaigns(id) on delete cascade,
  number      integer not null,
  status      varchar(16) not null default 'available'
              constraint ck_numbers_status check (status in ('available','reserved','paid')),
  order_id    uuid references public.orders(id),
  updated_at  timestamptz not null default now(),
  constraint uq_numbers_campaign_number unique (campaign_id, number),
  constraint ck_numbers_order_consistency check (
    (status = 'available' and order_id is null) or (status <> 'available' and order_id is not null)
  )
);
create index ix_numbers_campaign_status on public.numbers (campaign_id, status);
create index ix_numbers_order on public.numbers (order_id);

-- ---------------------------------------------------------------------------
-- order_numbers — índice único parcial impede o mesmo número em dois pedidos ativos
-- ---------------------------------------------------------------------------
create table public.order_numbers (
  id        bigint generated by default as identity primary key,
  order_id  uuid not null references public.orders(id) on delete cascade,
  number_id bigint not null references public.numbers(id),
  number    integer not null,
  active    boolean not null default true,
  constraint uq_order_numbers_order_number unique (order_id, number_id)
);
create unique index uq_order_numbers_active_number on public.order_numbers (number_id) where active;

-- ---------------------------------------------------------------------------
-- payments
-- ---------------------------------------------------------------------------
create table public.payments (
  id                  uuid primary key default gen_random_uuid(),
  order_id            uuid not null unique references public.orders(id),   -- uma cobrança por pedido
  provider            varchar(20) not null,
  provider_payment_id varchar(64) not null,
  idempotency_key     varchar(64) not null unique,
  status              varchar(16) not null default 'pending'
                      constraint ck_payments_status check (status in ('pending','approved','cancelled','expired','refunded','in_review','rejected')),
  provider_status     varchar(32) not null default '',
  status_detail       varchar(64) not null default '',
  amount_cents        integer not null,
  live_mode           boolean not null default false,
  qr_code             text not null default '',
  qr_code_base64      text not null default '',
  ticket_url          varchar(500) not null default '',
  expires_at          timestamptz,
  approved_at         timestamptz,
  last_synced_at      timestamptz,
  raw_last            jsonb not null default '{}'::jsonb,
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now(),
  constraint uq_payments_provider_id unique (provider, provider_payment_id)
);
create index ix_payments_status on public.payments (status);

-- ---------------------------------------------------------------------------
-- admin_users — vincula usuários do Supabase Auth ao painel
-- ---------------------------------------------------------------------------
create table public.admin_users (
  id         uuid primary key references auth.users(id) on delete cascade,
  email      varchar(254) not null unique,
  name       varchar(160) not null default '',
  active     boolean not null default true,
  created_at timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- audit_logs
-- ---------------------------------------------------------------------------
create table public.audit_logs (
  id          bigint generated by default as identity primary key,
  actor_type  varchar(16) not null,
  actor_id    varchar(64) not null default '',
  action      varchar(64) not null,
  entity_type varchar(32) not null default '',
  entity_id   varchar(64) not null default '',
  details     jsonb not null default '{}'::jsonb,
  created_at  timestamptz not null default now()
);
create index ix_audit_logs_entity on public.audit_logs (entity_type, entity_id);

-- ---------------------------------------------------------------------------
-- webhook_events — deduplicação de notificações
-- ---------------------------------------------------------------------------
create table public.webhook_events (
  id           bigint generated by default as identity primary key,
  provider     varchar(20) not null,
  request_id   varchar(100) not null,
  topic        varchar(40) not null default '',
  resource_id  varchar(64) not null default '',
  processed_at timestamptz,
  created_at   timestamptz not null default now(),
  constraint uq_webhook_events_request unique (provider, request_id)
);

-- ---------------------------------------------------------------------------
-- number_availability — ÚNICA tabela pública (Realtime). Sem dados pessoais e sem
-- distinção entre reservado e pago.
-- ---------------------------------------------------------------------------
create table public.number_availability (
  campaign_id uuid not null references public.campaigns(id) on delete cascade,
  number      integer not null,
  available   boolean not null,
  primary key (campaign_id, number)
);

create or replace function public.sync_number_availability() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'DELETE' then
    delete from public.number_availability where campaign_id = old.campaign_id and number = old.number;
    return old;
  end if;
  if tg_op = 'UPDATE' and (old.status = 'available') = (new.status = 'available') then
    return new;  -- reservado -> pago não muda a disponibilidade pública
  end if;
  insert into public.number_availability (campaign_id, number, available)
  values (new.campaign_id, new.number, new.status = 'available')
  on conflict (campaign_id, number) do update set available = excluded.available;
  return new;
end $$;

create trigger trg_numbers_availability
after insert or update of status or delete on public.numbers
for each row execute function public.sync_number_availability();

-- updated_at automático
create or replace function public.touch_updated_at() returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end $$;
create trigger trg_campaigns_touch before update on public.campaigns for each row execute function public.touch_updated_at();
create trigger trg_orders_touch before update on public.orders for each row execute function public.touch_updated_at();
create trigger trg_payments_touch before update on public.payments for each row execute function public.touch_updated_at();

-- ---------------------------------------------------------------------------
-- Row Level Security
-- ---------------------------------------------------------------------------
alter table public.campaigns          enable row level security;
alter table public.participants       enable row level security;
alter table public.orders             enable row level security;
alter table public.numbers            enable row level security;
alter table public.order_numbers      enable row level security;
alter table public.payments           enable row level security;
alter table public.admin_users        enable row level security;
alter table public.audit_logs         enable row level security;
alter table public.webhook_events     enable row level security;
alter table public.number_availability enable row level security;

-- Nenhuma política para as tabelas privadas => anon/authenticated não leem nada.
revoke all on public.participants, public.orders, public.payments, public.audit_logs,
              public.webhook_events, public.admin_users, public.order_numbers, public.numbers
       from anon, authenticated;

-- Leitura pública somente da disponibilidade
grant select on public.number_availability to anon, authenticated;
create policy "Disponibilidade é pública"
  on public.number_availability for select to anon, authenticated using (true);

-- Realtime: transmitir apenas a tabela de disponibilidade
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    execute 'alter publication supabase_realtime add table public.number_availability';
  end if;
end $$;
